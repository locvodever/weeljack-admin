/** `created` and `updated` are hours before the demo anchor. */
function ticket(
  number: number,
  subject: string,
  requester: string,
  priority: TicketPriority,
  status: TicketStatus,
  assignee: string,
  created: number,
  updated: number,
): Ticket {
  return {
    id: `WJ-${number}`,
    subject,
    requester,
    priority,
    status,
    assignee,
    created: hoursAgo(created),
    updated: hoursAgo(updated),
  };
}

